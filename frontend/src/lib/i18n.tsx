const storageKey = 'savage-worlds-language'

function translateText(text: string): string {
  const exactTranslation = translations[text]
  if (exactTranslation) return exactTranslation

  const dieRequirement = text.match(/^(.+?) d(4|6|8|10|12)\+$/)
  if (dieRequirement) return `${translateText(dieRequirement[1])} d${dieRequirement[2]}+`

  if (text.includes(', ')) {
    return text.split(', ').map(translateText).join(', ')
  }

  if (text.includes(' or ')) {
    return text.split(' or ').map(translateText).join(' lub ')
  }

  return text
}

function getInitialLanguage(): Language {
  try {
    return window.localStorage.getItem(storageKey) === 'pl' ? 'pl' : 'en'
  } catch {
    return 'en'
  }
}

export function LanguageProvider({ children }: PropsWithChildren) {
  const [language, setLanguage] = useState<Language>(getInitialLanguage)
  const queryClient = useQueryClient()
  const previousLanguage = useRef(language)

  useEffect(() => {
    document.documentElement.lang = language
    try {
      window.localStorage.setItem(storageKey, language)
    } catch {
      // Language selection remains available for this session when storage is disabled.
    }
  }, [language])

  useEffect(() => {
    if (previousLanguage.current === language) return

    previousLanguage.current = language
    void queryClient.invalidateQueries()
  }, [language, queryClient])

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      t: (text: string) => (language === 'pl' ? translateText(text) : text),
    }),
    [language],
  )

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}
